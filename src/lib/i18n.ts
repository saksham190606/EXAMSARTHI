export function getTranslation(lang: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.en;
  let text: string = dict[key] || translations.en[key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }

  return text;
}

export function useTranslation() {
  const language = useAccessibilityStore((state) => state.language);
  const setLanguage = useAccessibilityStore((state) => state.setLanguage);

  const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
    return getTranslation(language, key, params);
  };

  return { t, language, setLanguage };
}
